import io
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

def generate_invoice_pdf(invoice: dict) -> bytes:
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter

    # Header
    c.setFont("Helvetica-Bold", 16)
    business_info = invoice.get("business_info", {})
    c.drawString(50, height - 50, business_info.get("name", "Lax360 Store"))

    c.setFont("Helvetica", 10)
    c.drawString(50, height - 65, f"Category: {business_info.get('category', 'Universal Business')}")
    if business_info.get("gstin"):
        c.drawString(50, height - 80, f"GSTIN: {business_info.get('gstin')}")
    if business_info.get("phone"):
        c.drawString(50, height - 95, f"Phone: {business_info.get('phone')}")

    # Invoice info on right
    c.setFont("Helvetica-Bold", 12)
    c.drawRightString(width - 50, height - 50, f"TAX INVOICE")
    c.setFont("Helvetica", 10)
    c.drawRightString(width - 50, height - 65, f"Invoice #: {invoice.get('invoice_number')}")
    c.drawRightString(width - 50, height - 80, f"Date: {invoice.get('date')} {invoice.get('time')}")
    c.drawRightString(width - 50, height - 95, f"Payment: {invoice.get('payment_method')} ({invoice.get('payment_status')})")

    c.line(50, height - 110, width - 50, height - 110)

    # Customer info
    cust = invoice.get("customer", {})
    c.setFont("Helvetica-Bold", 10)
    c.drawString(50, height - 125, "Billed To:")
    c.setFont("Helvetica", 10)
    c.drawString(50, height - 140, f"Name: {cust.get('name', 'Walk-in Customer')}")
    if cust.get("phone"):
        c.drawString(50, height - 155, f"Phone: {cust.get('phone')}")
    if cust.get("gstin"):
        c.drawString(50, height - 170, f"GSTIN: {cust.get('gstin')}")

    # Table Header
    y = height - 200
    c.setFillColorRGB(0.95, 0.95, 0.95)
    c.rect(50, y - 5, width - 100, 20, fill=1, stroke=0)
    c.setFillColorRGB(0, 0, 0)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(55, y, "Item Description")
    c.drawString(260, y, "Qty & Unit")
    c.drawString(340, y, "Price")
    c.drawString(410, y, "GST")
    c.drawRightString(width - 55, y, "Total")

    # Table rows
    c.setFont("Helvetica", 9)
    y -= 20
    for item in invoice.get("items", []):
        c.drawString(55, y, item.get("name", "")[:35])
        c.drawString(260, y, f"{item.get('quantity')} {item.get('unit', 'pcs')}")
        c.drawString(340, y, f"₹{item.get('unit_price', 0.0):.2f}")
        c.drawString(410, y, f"{item.get('tax_rate', 0)}% (₹{item.get('tax_amount', 0.0):.2f})")
        c.drawRightString(width - 55, y, f"₹{item.get('line_total', 0.0):.2f}")
        y -= 18
        if y < 100:
            c.showPage()
            y = height - 50

    c.line(50, y, width - 50, y)
    y -= 20

    # Summary
    c.setFont("Helvetica", 10)
    c.drawRightString(width - 150, y, "Subtotal (Taxable):")
    c.drawRightString(width - 55, y, f"₹{invoice.get('subtotal', 0.0):.2f}")
    y -= 15
    c.drawRightString(width - 150, y, "Total GST (CGST + SGST):")
    c.drawRightString(width - 55, y, f"₹{invoice.get('tax_amount', 0.0):.2f}")
    y -= 15
    if invoice.get("discount_amount", 0.0) > 0:
        c.drawRightString(width - 150, y, "Discount:")
        c.drawRightString(width - 55, y, f"-₹{invoice.get('discount_amount', 0.0):.2f}")
        y -= 15

    c.setFont("Helvetica-Bold", 12)
    c.drawRightString(width - 150, y, "Grand Total:")
    c.drawRightString(width - 55, y, f"₹{invoice.get('grand_total', 0.0):.2f}")

    # Footer
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(50, 40, "Generated by Lax360 Billing SaaS • Universal POS & Invoicing System")

    c.save()
    buffer.seek(0)
    return buffer.getvalue()
